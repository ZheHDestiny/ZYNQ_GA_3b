"""Generate the synthesizable GA3B inverse-r^3 mantissa ROM.

The ROM stores two Q8.32 values for m in [1, 2]:
  even = GM * m**(-3/2)
  odd  = GM * 2**(-3/2) * m**(-3/2)

The force unit handles the remaining power-of-two exponent with shifts.  The
257th endpoint permits linear interpolation without a boundary special case.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "rtl" / "pure3_core" / "ga3b_pure3_inv_r3_lut.v"
FRAC_BITS = 32
GM = 1.0 / 256.0


def q32(value: float) -> int:
    return int(round(value * (1 << FRAC_BITS)))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--stdout", action="store_true")
    args = parser.parse_args()
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by scripts/gen/gen_pure3_inv_r3_lut.py; do not hand edit.",
        "`timescale 1ns/1ps",
        "module ga3b_pure3_inv_r3_lut(",
        "    input wire clk,",
        "    input wire [7:0] index,",
        "    input wire odd_exponent,",
        "    output reg [39:0] y0,",
        "    output reg [39:0] y1",
        ");",
        "    (* rom_style=\"block\" *) reg [79:0] mem [0:256];",
        "    initial begin",
    ]
    odd_factor = 2.0 ** -1.5
    for i in range(257):
        m = 1.0 + i / 256.0
        even = q32(GM * m ** -1.5)
        odd = q32(GM * odd_factor * m ** -1.5)
        lines.append(f"        mem[{i}] = 80'h{odd:010X}{even:010X};")
    lines += [
        "    end",
        "    reg [79:0] q0, q1;",
        "    always @(posedge clk) begin",
        "        q0 <= mem[index];",
        "        q1 <= mem[{1'b0,index} + 9'd1];",
        "        if (odd_exponent) begin",
        "            y0 <= q0[79:40]; y1 <= q1[79:40];",
        "        end else begin",
        "            y0 <= q0[39:0]; y1 <= q1[39:0];",
        "        end",
        "    end",
        "endmodule",
        "",
    ]
    payload = "\n".join(lines)
    if args.stdout:
        print(payload)
    else:
        OUT.write_text(payload, encoding="utf-8")
        print(OUT)


if __name__ == "__main__":
    main()
